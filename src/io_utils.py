"""
io_utils.py
------------
文件读写工具：
  - load_image: 读取图片为 RGB numpy 数组
  - save_point_cloud_ply: 保存点云为 .ply（可以被 Blender / MeshLab / Open3D 打开）
  - save_mesh_obj: 保存三角网格为 .obj（Blender / Unity / Godot 都能直接导入）

全部用纯 Python + numpy 实现，不依赖 Open3D，保证任何环境都能跑。
"""

from __future__ import annotations
import numpy as np


def load_image(path: str) -> np.ndarray:
    from PIL import Image
    img = Image.open(path).convert("RGB")
    return np.array(img)


def save_depth_png(depth: np.ndarray, path: str):
    """把深度图归一化并保存为灰度 png，方便肉眼检查。"""
    from PIL import Image
    d = depth.astype(np.float32)
    d = (d - d.min()) / (d.max() - d.min() + 1e-8)
    d = (d * 255).astype(np.uint8)
    Image.fromarray(d).save(path)


def save_point_cloud_ply(points: np.ndarray, colors: np.ndarray, path: str):
    """
    points: (N,3) float
    colors: (N,3) float in [0,1]
    """
    n = points.shape[0]
    colors_255 = np.clip(colors * 255, 0, 255).astype(np.uint8)
    with open(path, "w") as f:
        f.write("ply\nformat ascii 1.0\n")
        f.write(f"element vertex {n}\n")
        f.write("property float x\nproperty float y\nproperty float z\n")
        f.write("property uchar red\nproperty uchar green\nproperty uchar blue\n")
        f.write("end_header\n")
        for p, c in zip(points, colors_255):
            f.write(f"{p[0]:.5f} {p[1]:.5f} {p[2]:.5f} {c[0]} {c[1]} {c[2]}\n")


def save_mesh_obj(vertices: np.ndarray, faces: np.ndarray, colors: np.ndarray | None, path: str):
    """
    vertices: (N,3) float
    faces: (M,3) int, 0-based 索引
    colors: (N,3) float in [0,1] 或 None（OBJ 标准不支持顶点色，这里写成非标准的 vN r g b 扩展，
            大多数看图工具会忽略颜色列，Blender 导入时颜色可能需要额外设置材质）
    """
    with open(path, "w") as f:
        f.write("# Generated by img23d pipeline\n")
        for i, v in enumerate(vertices):
            if colors is not None:
                c = colors[i]
                f.write(f"v {v[0]:.5f} {v[1]:.5f} {v[2]:.5f} {c[0]:.4f} {c[1]:.4f} {c[2]:.4f}\n")
            else:
                f.write(f"v {v[0]:.5f} {v[1]:.5f} {v[2]:.5f}\n")
        for face in faces:
            # OBJ 索引从 1 开始
            f.write(f"f {face[0]+1} {face[1]+1} {face[2]+1}\n")
